def _mark_seen_message(message_identity: str, message_fingerprint: str = "") -> None:
    if not message_identity and not message_fingerprint:
        return
    with _seen_message_ids_lock:
        now = time.time()
        if message_identity:
            _seen_message_ids[message_identity] = now
        if message_fingerprint:
            _seen_link_message_fingerprints[message_fingerprint] = now
        _prune_seen_message_ids(now)
        _prune_seen_link_message_fingerprints(now)
        if len(_seen_message_ids) > _SEEN_MESSAGE_IDS_MAX:
            compacted = sorted(
                _seen_message_ids.items(),
                key=lambda item: float(item[1] or 0),
            )[-_SEEN_MESSAGE_IDS_MAX:]
            _seen_message_ids.clear()
            _seen_message_ids.update(compacted)
        if len(_seen_link_message_fingerprints) > _SEEN_MESSAGE_IDS_MAX:
            compacted = sorted(
                _seen_link_message_fingerprints.items(),
                key=lambda item: float(item[1] or 0),
            )[-_SEEN_MESSAGE_IDS_MAX:]
            _seen_link_message_fingerprints.clear()
            _seen_link_message_fingerprints.update(compacted)
    _save_seen_message_ids()


