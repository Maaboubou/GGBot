def _chat_info_name(chat) -> str:
    """Best-effort 读取 wxautox 子窗口对应的聊天名。"""
    try:
        info = chat.ChatInfo()
        if isinstance(info, dict):
            return str(info.get("chat_name") or info.get("name") or "").strip()
    except Exception:
        return ""
    return ""


def _get_actual_listener_names() -> list:
    """读取当前仍存在或已注册的 wxautox 监听名。失败时返回空列表。"""
    global last_listener_actual_snapshot, last_listener_actual_snapshot_at
    if not wx:
        return []

    names = set()
    try:
        sub_windows = wx.GetAllSubWindow()
    except Exception as e:
        logger.debug(f"获取监听子窗口列表失败: {e}")
        sub_windows = []

    for chat in sub_windows or []:
        name = _chat_info_name(chat)
        if name:
            names.add(name)

    # wxautox 的子窗口枚举偶发返回空；wx.listen 是实际监听线程使用的注册表。
    # 两者取并集，避免健康检查/恢复流程误判所有监听丢失。
    try:
        listen = getattr(wx, "listen", None)
        if isinstance(listen, dict):
            for name, value in listen.items():
                chat = value[0] if isinstance(value, tuple) and value else value
                registered_name = _chat_info_name(chat) or str(name or "").strip()
                if registered_name:
                    names.add(registered_name)
    except Exception as e:
        logger.debug("读取 wx.listen 注册表失败: %s", e)

    snapshot = sorted(names)
    last_listener_actual_snapshot = list(snapshot)
    last_listener_actual_snapshot_at = time.time()
    return snapshot


