def _control_is_foreground(control) -> bool:
    handle = _control_handle(control)
    return bool(handle and handle == _control_handle(_current_top_control()))


def _focus_browser_if_needed(browser_top_control) -> bool:
    if not browser_top_control:
        return False
    if _control_is_foreground(browser_top_control):
        return True
    if not _focus_control(browser_top_control, "微信内置浏览器"):
        return False
