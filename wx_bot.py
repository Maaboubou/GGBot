# 本机内部 API 调用必须绕过系统代理。
# Windows/Sparkle/Mihomo 环境里常有 HTTP_PROXY=127.0.0.1:7890；
# 如果该代理未运行，requests 会把本机 Web 请求也错误送进代理，
# 导致 wx_bot 收到消息但无法转发给主应用，summary_plus 等插件不会触发。
def _ensure_localhost_bypasses_proxy() -> None:
    local_hosts = ["127.0.0.1", "localhost", "::1"]
    for key in ("NO_PROXY", "no_proxy"):
        existing = os.environ.get(key, "")
        parts = [p.strip() for p in existing.split(",") if p.strip()]
        lower = {p.lower() for p in parts}
        changed = False
        for host in local_hosts:
            if host.lower() not in lower:
                parts.append(host)
                changed = True
        if changed or not existing:
            os.environ[key] = ",".join(parts)


