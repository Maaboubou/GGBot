def message_callback(msg, chat):
    """
    处理收到的消息回调函数
    参数:
        msg: 消息对象
        chat: 聊天对象
    """
    try:
        message_attr = getattr(msg, 'attr', None)
        # 自己发送的消息不转发给插件（避免回环）。wxautox4 41.x
        # 的 SelfMessage.sender 只是 "self"，不能作为群昵称信号。
        if message_attr == 'self':
            return

        # 只处理朋友发来的消息，忽略系统消息
        if message_attr != 'friend':
            return
            
        # 获取聊天名称
        chat_info = chat.ChatInfo() or {}
        chat_name = chat_info.get("chat_name", "Unknown")
        is_group_chat = str(chat_info.get("chat_type") or "").lower() == "group"
        sender_name = str(getattr(msg, "sender", "") or "").strip()

        try:
            content_str = str(msg.content).strip()
        except Exception:
            content_str = ""

        _record_listener_callback_activity(chat_name, msg, content_str)

        if _is_sender_blacklisted_for_chat(chat_name, sender_name):
            _record_listener_dropped_message(chat_name, "sender_blacklist", msg, content_str)
            logger.info("🚫 Sender 命中群/用户级黑名单，跳过所有插件处理: chat='%s' sender='%s'", chat_name, sender_name)
            return

        message_identity = _message_identity(chat_name, msg)
        if _has_seen_message_id(message_identity):
            _record_listener_dropped_message(chat_name, "seen_message_id", msg, content_str)
            logger.warning(
                "⚠️ 检测到 wxautox4 短时间重复/回放消息，已忽略: id=%s sender='%s' chat='%s' content='%s'",
                message_identity,
                getattr(msg, "sender", ""),
                chat_name,
                content_str[:50],
            )
            return

        message_fingerprint = _link_message_fingerprint(chat_name, msg, content_str)
        if _has_seen_link_message_fingerprint(message_fingerprint):
            _record_listener_dropped_message(chat_name, "seen_link_fingerprint", msg, content_str)
            logger.warning(
                "⚠️ 检测到 wxautox4 回放已处理链接内容，已忽略: fingerprint=%s id=%s sender='%s' chat='%s' content='%s'",
                message_fingerprint[:24],
                message_identity,
                getattr(msg, "sender", ""),
                chat_name,
                content_str[:50],
            )
            return

        # ---- 消息去重：防止 wxautox4 重复投递同一消息事件 ----
        _dedup_key = (msg.sender, chat_name, str(msg.content))
        _now = time.time()
        if _dedup_key in _dedup_cache and _now - _dedup_cache[_dedup_key] < _DEDUP_WINDOW_SEC:
            _record_listener_dropped_message(chat_name, "dedup_window", msg, content_str)
            logger.warning(f"⚠️ 检测到重复消息，已忽略: sender='{msg.sender}', chat='{chat_name}', content='{str(msg.content)[:30]}'")
            return
        _dedup_cache[_dedup_key] = _now
        # 顺便清理过期条目，避免无限增长
        expired = [k for k, t in _dedup_cache.items() if _now - t > _DEDUP_WINDOW_SEC * 5]
        for k in expired:
            del _dedup_cache[k]
        # ---- 去重结束 ----
        
        # 优化日志记录
        quote_content_raw = getattr(msg, 'quote_content', '') or ''
        quote_content_str = str(quote_content_raw)
        # 单行化：转义换行/回车，便于日志检索
        quote_content_one_line = quote_content_str.replace('\r', '\\r').replace('\n', '\\n')
        # 截断：最多 20 字（超出追加...）
        if len(quote_content_one_line) > 20:
            quote_content_one_line = quote_content_one_line[:20] + "..."
        quote_content_part = f", quote_content='{quote_content_one_line}'" if quote_content_one_line else ""
        logger.info(
            f"📥 Received message: "
            f"sender='{msg.sender}', "
            f"chat='{chat_name}', "
            f"type='{msg.type}', "
            f"content='{str(msg.content)}'"
            f"{quote_content_part}"
            
        )
        
        # 初始化额外数据
        url = None
        quote_image_path = None
        
        # 如果是链接或疑似链接消息，尝试获取URL（兼容部分客户端将链接标记为other/[链接]或link/[链接]）
        # 1) 直接从内容中提取 http(s) 链接
        if not url and ("http" in content_str or "https" in content_str):
            extracted_url = _extract_first_http_url(content_str)
            if extracted_url:
                url = extracted_url
                logger.info(f"✅ 从消息内容解析URL: {url}")

        # 1.5) 处理微信压缩的折叠文本：只要以“...更多”结尾，就尝试
        # 右键复制完整文本；最终以剪贴板中是否能提取到 URL 为准。
        if not url and _is_folded_copy_more_message(content_str):
            if check_summary_permission(chat_name):
                logger.info("🔗 检测到“...更多”折叠文本，尝试右键复制完整文本解析URL")
                url = resolve_url_from_message_copy(msg, timeout_sec=3.0)
            else:
                logger.info(f"🔗 检测到“...更多”折叠文本，但聊天 '{chat_name}' 未启用摘要功能，跳过右键复制解析")

        # 2) 处理被微信折叠的链接卡片：content 以 "[链接]" 开头（wxautox4 更新后可能带更多内容）
        link_message_id = None
        if not url and content_str.startswith("[链接]") and msg.type in ("other", "link"):
            link_message_id = cache_message_for_later(chat_name, msg, prefix="link")
            logger.info("🔗 检测到 [链接] 卡片消息，已缓存以便按需解析URL: %s:%s", chat_name, link_message_id)
            if not check_summary_permission(chat_name):
                logger.info(f"🔗 检测到 [链接] 卡片消息，但聊天 '{chat_name}' 未启用摘要功能，跳过点击操作")

        # 处理图片消息 - 缓存消息对象以供后续下载
        has_quote_image = False
        quote_image_path = None
        message_id = None
        normalized_quote_content = getattr(msg, 'quote_content', '')

        if msg.type == "quote":
            logger.info("📎 检测到引用消息")
            # 检查引用内容是否包含图片
            quote_content = getattr(msg, 'quote_content', '')
            # 兼容不同客户端/库版本：引用图片可能表现为 "[图片]" 或仅为 "图片"
            quote_content_stripped = str(quote_content).strip()
            if ('[图片]' in quote_content) or (quote_content_stripped == '图片'):
                logger.info("🖼️ 检测到引用图片，暂不下载（等待插件按需请求）")
                has_quote_image = True
                # 归一化：主程序与插件侧均以 "[图片]" 作为引用图片标记
                if quote_content_stripped == '图片' and '[图片]' not in str(quote_content):
                    logger.info("🧩 引用图片标记归一化: '图片' -> '[图片]'")
                normalized_quote_content = "[图片]"
            else:
                normalized_quote_content = quote_content

        # 为所有图片消息缓存消息对象
        if msg.type == "image":
            logger.info("🖼️ 检测到直接图片消息，缓存消息对象")
            # 缓存消息对象以供后续按需下载
            message_id = cache_message_for_later(chat_name, msg, prefix="image")
            logger.debug(f"🔄 缓存直接图片消息: {chat_name}:{message_id}")
        elif msg.type == "quote" and has_quote_image:
            logger.info("🖼️ 检测到引用图片，暂不下载（等待插件按需请求）")
            # 缓存消息对象以供后续按需下载
            message_id = cache_message_for_later(chat_name, msg, prefix="quote_image")
            logger.debug(f"🔄 缓存引用图片消息: {chat_name}:{message_id}")
        
        # 序列化消息内容
        # 如果成功解析出URL，则将mtype标记为link，便于主应用识别为链接事件
        resolved_mtype = getattr(msg, 'mtype', msg.type)
        if url:
            resolved_mtype = 'link'

        # 为图片消息生成message_id
        final_message_id = None
        if msg.type == "image":
            final_message_id = message_id
        elif has_quote_image:
            final_message_id = message_id
        elif link_message_id:
            final_message_id = link_message_id
        elif resolved_mtype == "link" or _is_link_like_message(msg, content_str):
            # 常规 URL 文本也需要保留原始 wxautox 消息对象，摘要生成完成后
            # 才能通过 message_id 调用 msg.quote(...) 引用回复。
            final_message_id = cache_message_for_later(chat_name, msg, prefix="link")
            logger.debug(f"🔄 缓存链接消息用于后续引用回复: {chat_name}:{final_message_id}")

        msg_data = {
            "content": msg.content,
            "sender": msg.sender,
            "sender_id": str(
                getattr(msg, "sender_id", None)
                or getattr(msg, "wxid", None)
                or ""
            ).strip() or None,
            "sender_remark": str(
                getattr(msg, "sender_remark", None) or ""
            ).strip() or None,
            "chat_name": chat_name,
            "is_group": is_group_chat,
            "type": msg.type,
            "mtype": resolved_mtype,  # 使用解析后的mtype
            "message_id": final_message_id,  # 消息ID，用于后续操作
            "url": url,  # 添加URL字段
            "quote_image_path": quote_image_path,  # 引用图片路径（延迟下载时为None）
            "quote_content": normalized_quote_content,  # 添加引用内容字段（已做引用图片标记归一化）
            "has_quote_image": has_quote_image,  # 标记是否有引用图片需要按需下载
            "timestamp": time.time(),  # 使用当前时间作为时间戳
        }
        
        # 发送到主应用
        try:
            response = requests.post(
                f"{MAIN_APP_URL}/api/internal/wechat_message",
                json=msg_data,
                timeout=30 # 30秒超时，足够图片下载
            )
            response.raise_for_status() # 如果请求失败则抛出异常
            _mark_seen_message(message_identity, message_fingerprint)
            _record_listener_forwarded_message(chat_name, msg, content_str)
            logger.debug(f"Message forwarded to main app, status: {response.status_code}")
        except requests.RequestException as e:
            logger.error(f"Failed to forward message to main app: {e}")

        # 校准在后台线程中执行；每群每 24 小时最多一次，不阻塞消息转发。
        if is_group_chat:
            _maybe_schedule_group_nickname_probe(chat_name)

    except Exception as e:
        logger.error(f"Error processing message: {e}")


