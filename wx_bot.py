class ColoredFormatter(logging.Formatter):
    """自定义彩色日志格式化器"""
    
    # ANSI颜色代码
    COLORS = {
        'DEBUG': '\033[36m',    # 青色
        'INFO': '\033[32m',     # 绿色
        'WARNING': '\033[33m',  # 黄色
        'ERROR': '\033[31m',    # 红色
        'CRITICAL': '\033[35m', # 紫色
        'RESET': '\033[0m'      # 重置颜色
    }
    
    def format(self, record):
        # 获取原始格式化的消息
        formatted = super().format(record)
        
        # 为不同级别添加颜色
        level_name = record.levelname
        if level_name in self.COLORS:
            # 在级别名称前后添加颜色代码
            formatted = formatted.replace(
                f"[{level_name}]", 
                f"{self.COLORS[level_name]}[{level_name}]{self.COLORS['RESET']}"
            )
            # 为整个消息添加绿色（INFO级别）
            if level_name == 'INFO':
                formatted = f"{self.COLORS['INFO']}{formatted}{self.COLORS['RESET']}"
        
        return formatted

