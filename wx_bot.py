def _activate_wechat_main_window(reason: str = "") -> bool:
    """Best-effort 激活微信主窗口，避免 wxautox 操作落在控制台/远控窗口上。"""
    if not wx:
        return False
    focused = False
    try:
        wx.Show()
        time.sleep(0.2)
    except Exception as e:
        logger.debug("激活微信主窗口失败: reason=%s error=%s", reason, e)

    for method_name in ("SwitchToChat",):
        try:
            method = getattr(wx, method_name, None)
            if callable(method):
                method()
                time.sleep(0.2)
                focused = True
        except Exception as e:
            logger.debug("微信主窗口切换失败: reason=%s method=%s error=%s", reason, method_name, e)

    try:
        main_window = None
        try:
            main_window = uia.WindowControl(ClassName="mmui::MainWindow", Name="微信")
        except Exception:
            main_window = None
        if main_window and _control_exists(main_window, 0.5):
            focused = _focus_control(main_window, "微信主窗口") or focused
            time.sleep(0.2)
    except Exception as e:
        logger.debug("通过 UIA 激活微信主窗口失败: reason=%s error=%s", reason, e)

    try:
        logger.info("🔄 激活微信主窗口[%s] foreground=%s", reason, _describe_control(_current_top_control()))
    except Exception:
        pass

    return focused


