@app.route('/api/send_message', methods=['POST'])
def send_message():
    """发送消息"""
    if not wx:
        return jsonify({"status": "error", "message": "WeChat not connected"}), 503
    
    data = request.json or {}
    who = data.get('who')
    msg = data.get('message')
    request_id = str(data.get('request_id') or "").strip()[:128]
    if not request_id:
        request_id = uuid.uuid4().hex
    
    if not who or not msg:
        return jsonify({"status": "error", "message": "Missing 'who' or 'message'"}), 400
        
    request_started_at = time.monotonic()
    logger.info(
        "Text send request received: request_id=%s chat=%s preview=%s...",
        request_id,
        who,
        msg[:50],
    )

    def _send_once() -> dict:
        lock_wait_started_at = time.monotonic()
        with wx_ui_lock:
            lock_wait_seconds = time.monotonic() - lock_wait_started_at
            outcome = send_text_with_retry(
                wx,
                who,
                msg,
                get_listener_chat=_get_actual_listener_chat,
                activate_main_window=_activate_wechat_main_window,
                logger=logger,
            )

        result = outcome.to_dict()
        result["lock_wait_ms"] = round(lock_wait_seconds * 1000, 1)
        return result

    try:
        result = outbound_text_deduplicator.run(
            ("text", request_id),
            _send_once,
        )
    except TimeoutError as e:
        logger.warning(
            "Duplicate text request is still in progress: request_id=%s chat=%s error=%s",
            request_id,
            who,
            e,
        )
        response = jsonify({
            "status": "busy",
            "message": "Original send request is still in progress",
            "request_id": request_id,
        })
        response.status_code = 503
        response.headers["Retry-After"] = "5"
        return response
    except Exception as e:
        logger.error(
            "Text send orchestration failed: request_id=%s chat=%s error=%s",
            request_id,
            who,
            e,
            exc_info=True,
        )
        return jsonify({
            "status": "error",
            "message": str(e),
            "request_id": request_id,
        }), 500

    attempts = result.get("attempts") or []
    last_attempt = attempts[-1] if attempts else {}
    total_ms = round((time.monotonic() - request_started_at) * 1000, 1)
    response_body = {
        "status": "success" if result.get("success") else "error",
        "message": "Message sent" if result.get("success") else "Failed to send message",
        "request_id": request_id,
        "route": last_attempt.get("route"),
        "attempt_count": len(attempts),
        "lock_wait_ms": result.get("lock_wait_ms"),
        "send_elapsed_ms": result.get("elapsed_ms"),
        "total_elapsed_ms": total_ms,
        "attempts": attempts,
    }

    if result.get("success"):
        _record_listener_outbound_activity(who, "text", msg)
        logger.info(
            "Text send completed: request_id=%s chat=%s route=%s attempts=%s "
            "lock_wait_ms=%s send_ms=%s total_ms=%s",
            request_id,
            who,
            response_body["route"],
            response_body["attempt_count"],
            response_body["lock_wait_ms"],
            response_body["send_elapsed_ms"],
            total_ms,
        )
        return jsonify(response_body)

    logger.error(
        "Text send failed: request_id=%s chat=%s attempts=%s lock_wait_ms=%s "
        "send_ms=%s total_ms=%s last_response=%s last_error=%s",
        request_id,
        who,
        response_body["attempt_count"],
        response_body["lock_wait_ms"],
        response_body["send_elapsed_ms"],
        total_ms,
        last_attempt.get("response"),
        last_attempt.get("error"),
    )
    return jsonify(response_body), 500


