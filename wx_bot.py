def quote_message():
    """引用缓存中的原消息并回复文本。"""
    if not wx:
        return jsonify({"status": "error", "message": "WeChat not connected"}), 503

    data = request.json or {}
    chat_name = data.get('chat_name')
    message_id = data.get('message_id')
    reply_text = data.get('message')

    if not chat_name or not message_id or not reply_text:
        return jsonify({
            "status": "error",
            "message": "Missing 'chat_name', 'message_id' or 'message'"
        }), 400

    try:
        cached_messages = message_cache.get(chat_name, {})
        original_message = cached_messages.get(message_id)
        if original_message is None:
            return jsonify({
                "status": "error",
                "message": f"Message not found in cache: {chat_name}:{message_id}"
            }), 404

        quote = getattr(original_message, 'quote', None)
        if not callable(quote):
            return jsonify({
                "status": "error",
                "message": "Current wxautox message object does not support quote()"
            }), 501

        logger.info("Replying with quote to %s:%s: %s...", chat_name, message_id, reply_text[:50])
        with wx_ui_lock:
            result = quote(reply_text)

        if result:
            _record_listener_outbound_activity(chat_name, "quote", reply_text)
            return jsonify({"status": "success", "message": "Quoted message sent"})

        result_message = result.get('message') if isinstance(result, dict) else str(result)
        return jsonify({
            "status": "error",
            "message": result_message or "Failed to quote message"
        }), 500
    except Exception as e:
        logger.error("Error replying with quote: %s", e, exc_info=True)
        return jsonify({"status": "error", "message": str(e)}), 500

